import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { discover, allowedTarget, verifyPageService } from '../dist/discovery.js';
import { fetchBundleFromOrigin, computeBundleSha256, SUPPORTED_BUNDLES } from '../dist/bundle.js';
import { rendererSources, nativeSources, createCoverage, coverageMarkdown } from '../dist/coverage.js';
import { loadDictionary } from '../dist/dictionary.js';
const root=fileURLToPath(new URL('../',import.meta.url));const app='/Applications/Antigravity.app';
if(!process.argv.includes('--resources-only'))throw new Error('此工具只扫描已验证应用的静态资源，请指定 --resources-only；当前可见界面取证请使用 node tools/real-acceptance.mjs；自动遍历仅保留为开发API，暂无原生入口');
const endpoint=await discover(app,join(homedir(),'Library/Application Support/Antigravity'));
if(!endpoint)throw new Error('应用未运行');
const targets=await(await fetch(`http://127.0.0.1:${endpoint.port}/json/list`,{signal:AbortSignal.timeout(3000),redirect:'error'})).json();
const target=targets.find(t=>allowedTarget(t));if(!target||!await verifyPageService(target.url,app))throw new Error('页面服务身份未确认');
const origin=new URL(target.url).origin,source=await fetchBundleFromOrigin(origin),hash=computeBundleSha256(source);
if(SUPPORTED_BUNDLES.get(endpoint.appVersion)!==hash)throw new Error('未知应用版本或界面包指纹');
const resources=await rendererSources(origin,source,new AbortController().signal,()=>{});resources.resources.push(...await nativeSources(app));
const dictionary=await loadDictionary(join(root,'dict'),join(homedir(),'Library/Application Support/GravityBox/词典'));
const report=createCoverage(resources.resources,dictionary,endpoint.appVersion,hash,resources.skipped);
const version=JSON.parse(await readFile(join(root,'package.json'))).version;const out=join(root,'质检报告',`${version}-改造验收`,'全面扫描');await mkdir(out,{recursive:true});
await writeFile(join(out,'静态资源清单.json'),JSON.stringify(report,null,2));await writeFile(join(out,'静态覆盖清单.md'),coverageMarkdown(report));
console.log(JSON.stringify({resources:report.resources.length,entries:report.entries.length,counts:report.counts,skipped:report.skipped,out}));
